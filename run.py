#!/usr/bin/env python3
"""
run.py

Compare files between folders and generate reports.

Dependencies
------------
pip install tqdm

Examples
--------

Analyse all files:

    python run.py -s "t:\\Pictures" -t "d:\\Other"

Analyse only png and jpg:

    python run.py -s "t:\\Pictures" -t "d:\\Other" -ft "png,jpg"

Apply report:

    python run.py -s "t:\\Pictures" \
                  -op a \
                  -r "analyse_20261021_120000.json" \
                  -d "d:\\Backup"

"""

from __future__ import annotations

import argparse
import json
import shutil
import sys

from collections import defaultdict
from datetime import datetime
from pathlib import Path

from tqdm import tqdm


# ==========================================================
# Helpers
# ==========================================================


def error(message: str) -> None:
    print(f"\nERROR: {message}", file=sys.stderr)
    sys.exit(1)


def create_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        formatter_class=argparse.RawTextHelpFormatter,
        description="""
Compare files by filename and size.

Arguments
---------
-s, --source
    Source folder (mandatory)

-t, --target
    Target folder (mandatory for operation r)

-ft
    Comma separated file extensions.
    Example:
        png,jpg,txt

-op, --operation
    r = read/analyse (default)
    a = apply report

-r, --report
    Report JSON file generated by analyse mode.
    Mandatory for operation a.

-d, --destination
    Empty destination folder.
    Mandatory for operation a.

Examples
--------
python run.py -s "t:\\Pictures" -t "d:\\Other"

python run.py -s "t:\\Pictures" -t "d:\\Other" -ft "png,jpg"

python run.py -s "t:\\Pictures" -op a ^
              -r analyse_20261021_120000.json ^
              -d "d:\\Backup"

Dependency
----------
pip install tqdm
"""
    )

    parser.add_argument(
        "-s",
        "--source",
        required=True,
        help="Source folder"
    )

    parser.add_argument(
        "-t",
        "--target",
        help="Target folder"
    )

    parser.add_argument(
        "-ft",
        help="File extensions separated by commas"
    )

    parser.add_argument(
        "-op",
        "--operation",
        default="r",
        choices=["r", "R", "a", "A"],
        help="r=read (default), a=apply"
    )

    parser.add_argument(
        "-r",
        "--report",
        help="JSON report file"
    )

    parser.add_argument(
        "-d",
        "--destination",
        help="Destination folder"
    )

    return parser


# ==========================================================
# Validation
# ==========================================================


def validate_source(source: Path) -> None:

    if not source.exists():
        error(f"Source folder not found: {source}")

    if not source.is_dir():
        error(f"Source path is not a folder: {source}")


def validate_read_mode(
    source: Path,
    target: Path
) -> None:

    if not target:
        error("Target folder is mandatory when operation is 'r'.")

    if not target.exists():
        error(f"Target folder not found: {target}")

    if not target.is_dir():
        error(f"Target path is not a folder: {target}")

    src = source.resolve()
    tgt = target.resolve()

    if src == tgt:
        error(
            "Source and target folders cannot be the same."
        )

    try:
        tgt.relative_to(src)

        error(
            "Target folder cannot be a subfolder "
            "of source folder."
        )

    except ValueError:
        pass


def validate_apply_mode(
    report_file: Path,
    destination: Path
) -> None:

    if report_file is None:
        error(
            "Report file is mandatory "
            "when operation is 'a'."
        )

    if not report_file.exists():
        error(
            f"Report file not found: {report_file}"
        )

    try:
        with open(
            report_file,
            "r",
            encoding="utf-8"
        ) as f:
            json.load(f)

    except Exception as ex:
        error(
            f"Invalid JSON report file. {ex}"
        )

    if destination is None:
        error(
            "Destination folder is mandatory "
            "when operation is 'a'."
        )

    if destination.exists():

        if not destination.is_dir():
            error(
                f"Destination is not a folder: "
                f"{destination}"
            )

        if any(destination.iterdir()):
            error(
                f"Destination folder must be empty: "
                f"{destination}"
            )

    else:
        destination.mkdir(
            parents=True,
            exist_ok=True
        )


# ==========================================================
# Files
# ==========================================================


def parse_extensions(
    value: str | None
) -> set[str] | None:

    if not value:
        return None

    return {
        ext.strip().lower().lstrip(".")
        for ext in value.split(",")
        if ext.strip()
    }


def extension_matches(
    file_path: Path,
    extensions: set[str] | None
) -> bool:

    if extensions is None:
        return True

    return (
        file_path.suffix.lower().lstrip(".")
        in extensions
    )


def get_files(
    root: Path,
    extensions: set[str] | None
):

    for item in root.rglob("*"):

        if not item.is_file():
            continue

        if extension_matches(item, extensions):
            yield item


def count_files(
    root: Path,
    extensions: set[str] | None
) -> int:

    return sum(
        1
        for _ in get_files(
            root,
            extensions
        )
    )


# ==========================================================
# Report
# ==========================================================


def create_run_section(args) -> dict:

    run = {
        "source": str(Path(args.source)),
        "operation": args.operation.lower()
    }

    if args.target:
        run["target"] = str(Path(args.target))

    if args.ft:
        run["file_types"] = args.ft

    if args.report:
        run["report"] = args.report

    if args.destination:
        run["destination"] = args.destination

    return run


def build_target_index(
    target: Path,
    extensions: set[str] | None
):

    print("\nCounting target files...")

    total_target_files = count_files(
        target,
        extensions
    )

    print(
        f"Target files to index: "
        f"{total_target_files:,}"
    )

    index = defaultdict(list)

    print("\nIndexing target folder...")

    for file in tqdm(
        get_files(target, extensions),
        total=total_target_files,
        desc="Target indexing",
        unit="file",
        colour="green"
    ):

        try:

            key = (
                file.name.lower(),
                file.stat().st_size
            )

            index[key].append(str(file))

        except Exception:
            continue

    print(
        f"Indexed files: "
        f"{total_target_files:,}"
    )

    return index


def analyse(
    source: Path,
    target: Path,
    extensions: set[str] | None,
    args
) -> dict:

    target_index = build_target_index(
        target,
        extensions
    )

    print("\nCounting source files...")

    total_files = count_files(
        source,
        extensions
    )

    print(
        f"\nSource files to analyse: "
        f"{total_files:,}"
    )

    report = {
        "run": create_run_section(args),
        "duplicates": [],
        "notfound": []
    }

    found_count = 0
    notfound_count = 0

    for src_file in tqdm(
        get_files(source, extensions),
        total=total_files,
        desc="Analysing",
        unit="file"
    ):

        try:

            key = (
                src_file.name.lower(),
                src_file.stat().st_size
            )

            matches = target_index.get(
                key,
                []
            )

            if matches:

                found_count += 1

                report["duplicates"].append(
                    {
                        "src": str(src_file),
                        "targets": matches
                    }
                )

            else:

                notfound_count += 1

                report["notfound"].append(
                    str(src_file)
                )

        except Exception:
            continue

    report["statistics"] = {
        "total_analysed": total_files,
        "found": found_count,
        "notfound": notfound_count
    }

    return report

def print_summary(report: dict) -> None:

    stats = report.get("statistics", {})

    print("\n")
    print("=" * 60)
    print("ANALYSIS COMPLETED")
    print("=" * 60)
    print(
        f"Total analysed : "
        f"{stats.get('total_analysed', 0):,}"
    )
    print(
        f"Found          : "
        f"{stats.get('found', 0):,}"
    )
    print(
        f"Not found      : "
        f"{stats.get('notfound', 0):,}"
    )
    print("=" * 60)

def save_report(report: dict) -> Path:

    timestamp = datetime.now().strftime(
        "%Y%m%d_%H%M%S"
    )

    report_file = (
        Path(__file__).parent
        / f"analyse_{timestamp}.json"
    )

    with open(
        report_file,
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(
            report,
            f,
            indent=4,
            ensure_ascii=False
        )

    return report_file


# ==========================================================
# Display
# ==========================================================


def print_duplicates(report: dict) -> None:

    print("\n")
    print("=" * 60)
    print("DUPLICATES")
    print("=" * 60)

    if not report["duplicates"]:
        print("No duplicates found.")
        return

    for item in report["duplicates"]:

        print(f"\nSRC: {item['src']}")

        for target in item["targets"]:
            print(f"   -> {target}")


def print_notfound(report: dict) -> None:

    print("\n")
    print("=" * 60)
    print("NOT FOUND")
    print("=" * 60)

    if not report["notfound"]:
        print("No missing files.")
        return

    for file in report["notfound"]:
        print(file)


# ==========================================================
# Apply
# ==========================================================


def load_report(
    report_file: Path
) -> dict:

    with open(
        report_file,
        "r",
        encoding="utf-8"
    ) as f:

        return json.load(f)


def apply_report(
    report: dict,
    source: Path,
    destination: Path
) -> None:

    not_found_files = report.get(
        "notfound",
        []
    )

    print(
        f"\nFiles to copy: "
        f"{len(not_found_files):,}"
    )

    copied = 0

    for file_str in tqdm(
        not_found_files,
        desc="Copying",
        unit="file"
    ):

        source_file = Path(file_str)

        if not source_file.exists():

            print(
                f"\nWARNING: file missing -> "
                f"{source_file}"
            )

            continue

        try:

            relative_path = (
                source_file.resolve()
                .relative_to(
                    source.resolve()
                )
            )

        except ValueError:

            print(
                f"\nWARNING: ignored "
                f"{source_file}"
            )

            continue

        destination_file = (
            destination /
            relative_path
        )

        destination_file.parent.mkdir(
            parents=True,
            exist_ok=True
        )

        shutil.copy2(
            source_file,
            destination_file
        )

        copied += 1

    print("\n")
    print("=" * 60)
    print("COPY COMPLETED")
    print("=" * 60)
    print(f"Copied files : {copied:,}")
    print("=" * 60)


# ==========================================================
# Main
# ==========================================================


def main():

    parser = create_parser()
    args = parser.parse_args()

    operation = (
        args.operation.lower()
    )

    source = Path(args.source)

    validate_source(source)

    if operation == "r":

        if not args.target:
            error(
                "Target folder is mandatory "
                "when operation is 'r'."
            )

        target = Path(args.target)

        validate_read_mode(
            source,
            target
        )

        extensions = parse_extensions(
            args.ft
        )

        report = analyse(
            source,
            target,
            extensions,
            args
        )

        print_duplicates(report)
        print_notfound(report)

        report_file = save_report(
            report
        )

        print(
            f"\nReport created:"
            f"\n{report_file}"
        )

        print_summary(report)

    else:

        report_file = Path(
            args.report
        )

        destination = Path(
            args.destination
        )

        validate_apply_mode(
            report_file,
            destination
        )

        report = load_report(
            report_file
        )

        apply_report(
            report,
            source,
            destination
        )


if __name__ == "__main__":
    main()